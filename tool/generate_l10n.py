def main() -> None:
    langs = {"en": EN, **{k: v for k, v in TRANSLATIONS.items()}, **remaining_langs()}
    ROOT.mkdir(parents=True, exist_ok=True)
    for lang, table in langs.items():
        missing = [k for k in EN if k not in table]
        extra = [k for k in table if k not in EN]
        if missing or extra:
            raise SystemExit(f"{lang}: missing={missing} extra={extra}")
        ordered = {k: table[k] for k in EN}
        path = ROOT / f"{lang}.json"
        path.write_text(json.dumps(ordered, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {path.name} ({len(ordered)} keys)")
    for stale in ROOT.glob("*.json"):
        if stale.stem not in langs:
            stale.unlink()
            print(f"removed {stale.name}")


